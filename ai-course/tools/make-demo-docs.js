// usage: node make-demo-docs.js <outDir>
const fs = require('fs');
const path = require('path');
const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell, WidthType, AlignmentType,
  BorderStyle, ShadingType, Footer, PageNumber, TabStopType,
} = require('docx');

const out = process.argv[2];
fs.mkdirSync(out, { recursive: true });

const rub = n => n.toLocaleString('ru-RU').replace(/ | /g, ' ');
const P = (text, o = {}) => new Paragraph({
  alignment: o.align || AlignmentType.JUSTIFIED,
  spacing: { after: o.after ?? 100, before: o.before ?? 0, line: o.line || 276 },
  indent: o.indent ? { firstLine: o.indent } : undefined,
  keepNext: o.keepNext,
  children: (Array.isArray(text) ? text : [text]).map(t => typeof t === 'string'
    ? new TextRun({ text: t, bold: o.bold, size: o.size, font: o.font, color: o.color, italics: o.italics })
    : new TextRun({ font: o.font, size: o.size, ...t })),
});
const border = { style: BorderStyle.SINGLE, size: 4, color: '808080' };
const borders = { top: border, bottom: border, left: border, right: border };
const cell = (text, w, o = {}) => new TableCell({
  width: { size: w, type: WidthType.DXA }, borders,
  shading: o.head ? { type: ShadingType.CLEAR, color: 'auto', fill: o.fill || 'E7ECF3' } : undefined,
  margins: { top: 60, bottom: 60, left: 100, right: 100 },
  children: [P(String(text), { align: o.align || AlignmentType.LEFT, bold: o.head || o.bold, after: 0, size: o.size || 20, font: o.font })],
});
const table = (cols, rows, o = {}) => new Table({
  width: { size: cols.reduce((a, b) => a + b, 0), type: WidthType.DXA },
  columnWidths: cols,
  rows: rows.map((r, i) => new TableRow({
    tableHeader: i === 0,
    children: r.map((t, j) => cell(t, cols[j], { head: i === 0, font: o.font, fill: o.fill,
      bold: o.boldLast && i === rows.length - 1,
      align: j >= (o.numFrom ?? 99) ? AlignmentType.RIGHT : AlignmentType.LEFT })),
  })),
});
const footer = label => new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [
  new TextRun({ text: label + ' · стр. ', size: 16, color: '808080' }),
  new TextRun({ children: [PageNumber.CURRENT], size: 16, color: '808080' }),
] })] });
const page = { size: { width: 11906, height: 16838 }, margin: { top: 1134, bottom: 1134, left: 1418, right: 850 } };
const save = async (doc, name) => { fs.writeFileSync(path.join(out, name), await Packer.toBuffer(doc)); console.log('saved', name); };

