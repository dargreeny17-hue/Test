// ---------------- Три КП ----------------
async function kp(o) {
  const F = 'Arial';
  const sum = o.rows.reduce((a, r) => a + r[3] * r[2], 0);
  const rows = [['№', 'Наименование', 'Кол‑во', `Цена, руб.${o.vatNote}`, `Сумма, руб.${o.vatNote}`]]
    .concat(o.rows.map((r, i) => [String(i + 1), r[0], String(r[2]), r[3] ? rub(r[3]) : 'включено', r[3] ? rub(r[3] * r[2]) : 'включено']))
    .concat([['', `ИТОГО${o.vatNote}`, '', '', rub(o.statedTotal ?? sum)]]);
  const doc = new Document({
    styles: { default: { document: { run: { font: F, size: 21 } } } },
    sections: [{ properties: { page }, footers: { default: footer('Учебный документ курса «ИИ‑команда». Компании и лица вымышлены') }, children: [
      P(o.company, { bold: true, size: 32, color: o.color, font: F, align: AlignmentType.LEFT, after: 0 }),
      P(o.tagline, { size: 18, color: '666666', font: F, align: AlignmentType.LEFT, after: 60 }),
      P('[АДРЕС, ТЕЛЕФОН, САЙТ УДАЛЕНЫ]', { size: 16, color: '999999', font: F, align: AlignmentType.LEFT, after: 300 }),
      P(`Исх. № ${o.num} от ${o.date}`, { size: 20, font: F, align: AlignmentType.LEFT, after: 0 }),
      P('Руководителю отдела закупок Компании Б', { size: 20, font: F, align: AlignmentType.RIGHT, after: 300 }),
      P('КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ', { bold: true, size: 28, font: F, align: AlignmentType.CENTER, after: 60 }),
      P('на поставку электрического погрузчика', { size: 22, font: F, align: AlignmentType.CENTER, after: 240 }),
      P(o.intro, { font: F, after: 200 }),
      table([500, 4600, 900, 1700, 1938], rows, { font: F, numFrom: 2, boldLast: true, fill: o.fill }),
      P('Условия поставки', { bold: true, font: F, before: 280, after: 100, align: AlignmentType.LEFT }),
      table([3200, 6438], o.terms.map(t => [t[0], t[1]]).reduce((a, r) => (a.push(r), a), [['Параметр', 'Условие']]), { font: F, fill: o.fill }),
      ...(o.notes || []).map(n => P(n, { font: F, size: 19, color: '444444', before: 120, after: 0 })),
      P(o.sign, { font: F, before: 400, align: AlignmentType.LEFT }),
    ] }],
  });
  await save(doc, o.file);
  return { sum, stated: o.statedTotal ?? sum };
}

